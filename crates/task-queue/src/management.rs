//! 队列（queue）在内部清理和关闭时返回的有限进度。
//!
//! 本模块（module）只定义返回数据，不持有队列（queue），不执行任务（Task），
//! 也不决定调用者何时完成运行时（runtime）关闭。

/// 一次有限清理操作的进度；不向调用者交出待清理原值。
///
/// 队列（queue）负责移除原内容、在合法线程（thread）清理或移交，并维护自己的状态和数量。
/// `MoreWork`表示本次明确范围尚有责任，仍由来源保管，调用者可随后继续同一操作。
/// `Complete`只确认对应范围的来源责任完成或合法移交，不确认原异步计算（Future）
/// 已析构（drop）、任务（Task）全部退出、其它句柄（handle）已释放或整个运行时（runtime）已关闭。
/// 开放清理、取消（cancellation）清理和关闭范围不同，不能互相代替完成证明。
// @trace 1
pub enum QueueCleanupProgress {
    /// 当前清理范围已处理完；关闭操作还须已完成或移交该来源的全部关闭责任。
    Complete,
    /// 当前范围仍有待处理责任；不要求本次已经取得或清理任何原值。
    MoreWork,
}
