//! 队列（queue）清理和关闭共同使用的进度与交付结果。
//!
//! 本模块（module）只定义返回数据，不持有队列（queue），不执行任务（Task），
//! 也不决定调用者何时完成运行时（runtime）关闭。

/// 一次有限管理操作的结果；`B`持有本次已经交给调用者的原内容。
///
/// 两种变体（variant）中的`B`都可以为空。返回后调用者负责其中内容的合法后续处理；
/// 队列（queue）继续保有未交出的责任。`Complete`只确认本次管理范围已完成或合法移交，
/// 不确认任务（Task）已结束、原异步计算（Future）已析构（drop）或其它句柄（handle）已释放。
/// 本类型（type）不强制`B`可克隆（Clone）、可跨线程转移（Send）或使用特定容器。
// @trace 1
pub enum QueueCleanupProgress<B> {
    /// 当前清理范围已处理完；关闭操作还须已完成或移交该来源的全部关闭责任。
    Complete(B),
    /// 本次已有内容交出，但原管理范围仍有责任；也允许尚无内容可交出。
    MoreWork(B),
}
